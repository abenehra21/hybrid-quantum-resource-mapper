"""Write results/phase1_baselines.md and results/phase2_prediction.md from the logs and dataset."""
import math
from pathlib import Path

import pandas as pd

from hybrid_mapper.baselines import LOG_PATH
from hybrid_mapper.dataset import TRANSPILE_TIMEOUT_S as TIMEOUT
from hybrid_mapper.predict import evaluate, load_dataset, outcome_models
from hybrid_mapper.rules import load_rules

RESULTS = Path(__file__).resolve().parent.parent / "results"
STRATEGY_FOR = {"CLASSICAL": "classical", "HYBRID": "hybrid"}  # REDESIGN runs nothing


def md_table(df: pd.DataFrame, floatfmt: str = ".3g") -> str:
    def cell(v):
        if isinstance(v, float):
            return "—" if math.isnan(v) else format(v, floatfmt)
        return str(v)

    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def cost(row, w) -> float:
    return w["w_time"] * row.projected_runtime_s + w["w_energy"] * row.energy_j_est + w["w_qpu"] * row.qpu_seconds_est


def phase1(log: pd.DataFrame) -> str:
    w = load_rules()["oracle_weights"]
    if "run_id" in log:  # one coherent run: the latest full one, else the latest quick one
        runs = log[log["mode"] == "full"] if (log["mode"] == "full").any() else log
        log = runs[runs.run_id == runs.run_id.max()]
    log = log.sort_values("timestamp").groupby(["workload", "strategy"]).tail(1)
    log = log.assign(rel_error=log.error / log.exact.abs(), J=[cost(r, w) for r in log.itertuples()])
    picks = {"Classical-only": [], "Hybrid (always)": [], "Rule-based mapper": [], "Oracle": []}
    per_task = []
    for name, runs in log.groupby("workload"):
        by = runs.set_index("strategy")
        ok = by[by.success.astype(str) == "True"]
        oracle = ok.J.idxmin() if len(ok) else by.rel_error.idxmin()
        decision = by.decision.iloc[0]
        mapped = STRATEGY_FOR.get(decision)
        picks["Classical-only"].append(by.loc["classical"])
        picks["Hybrid (always)"].append(by.loc["hybrid"])
        picks["Oracle"].append(by.loc[oracle])
        if mapped:
            picks["Rule-based mapper"].append(by.loc[mapped])
        per_task.append({"workload": name, "rule decision": f"{decision} ({by.fired_rule.iloc[0]})",
                         "oracle": oracle, "match": mapped == oracle,
                         "regret J": (by.loc[mapped].J - by.loc[oracle].J) if mapped else math.nan,
                         "hybrid rel. error": by.loc["hybrid"].rel_error})
    metrics = {
        "Runtime, projected (s)": lambda d: d.projected_runtime_s.mean(),
        "Energy, estimated (J)": lambda d: d.energy_j_est.mean(),
        "Accuracy (mean relative error)": lambda d: d.rel_error.mean(),
        "QPU time, estimated (s)": lambda d: d.qpu_seconds_est.mean(),
        "Number of shots": lambda d: d.shots.mean(),
        "Success rate": lambda d: (d.success.astype(str) == "True").mean(),
        "Communication overhead (QPU round trips)": lambda d: d.qpu_calls.mean(),
    }
    table = pd.DataFrame({"Metric": list(metrics)} | {
        col: [f(pd.DataFrame(rows)) if rows else math.nan for f in metrics.values()] for col, rows in picks.items()})
    natural = lambda s: s.str.replace(r"\d+", lambda m: m.group().zfill(4), regex=True)  # maxcut6 before maxcut10
    tasks = pd.DataFrame(per_task).sort_values("workload", key=natural)
    return f"""# Phase 1 results: rule-based mapper vs baselines

Generated by `python -m hybrid_mapper report` from `logs/decisions.csv` (the latest full `baselines` run).
Hybrid runs are simulated on qiskit-aer with the FakeFez noise model; their *projected* runtime replaces
simulation time with estimated QPU time (shots / backend throughput). Energy uses the assumed power figures
in `config/rules.yaml`. Quantum-only is not reported: variational algorithms have no quantum-only form.
The AI hybrid column arrives in Phase 3.

## Proposal metric table (mean per workload)

{md_table(table)}

## Per-workload decisions

Oracle = cheapest strategy (cost J from `oracle_weights`) among those meeting the accuracy target
(relative error <= `success_rel_error`).

{md_table(tasks)}

**Decision accuracy vs oracle:** {tasks.match.mean():.0%} of {len(tasks)} workloads.
**Mean regret:** {tasks['regret J'].mean():.3g} (cost units).
"""


def phase2(all_rows: pd.DataFrame, log: pd.DataFrame | None) -> str:
    timeouts = all_rows[all_rows.timed_out]
    df = all_rows[~all_rows.timed_out].reset_index(drop=True)
    acc, agree = evaluate(df)
    slow = df[df.transpile_s > 10]
    slow_list = ", ".join(f"{f}/{e} n={n} on {b}" for f, e, n, b in
                          sorted({(r.family, r.entanglement, r.n_qubits, r.backend) for r in slow.itertuples()}))
    parts = [f"""# Phase 2 results: resource prediction

Generated by `python -m hybrid_mapper report` from `data/resources.csv`
({len(df)} rows: {df.family.nunique()} workload families x {df.backend.nunique()} backends,
{df.n_qubits.min()}–{df.n_qubits.max()} qubits). Labels are exact transpiler outputs (optimization_level=3).
MAPE = mean |predicted − exact| / exact. R² on raw counts.

**Exact transpilation is not always cheap:** median {df.transpile_s.median():.2f} s, but {len(slow)} transpiles took
over 10 s (max {df.transpile_s.max():.0f} s): {slow_list or "none"}. Most are circuits whose interaction graph
has no exact embedding in the coupling map (e.g. 50/70/90/110-qubit rings on heavy-hex, ~28 s vs ~1 s for rings
that embed) or dense random circuits, where Qiskit's VF2 layout search runs to its limit before routing.
{len(timeouts)} transpiles hit the {TIMEOUT} s hard timeout. The predictors answer in milliseconds regardless.
"""]
    for split, block in acc.groupby("split", sort=False):
        wide = block.pivot(index="target", columns="model", values="MAPE")[["analytic", "power-law", "gbt"]]
        r2 = block.pivot(index="target", columns="model", values="R2")[["analytic", "power-law", "gbt"]]
        wide.columns = [f"MAPE {c}" for c in wide.columns]
        r2.columns = [f"R² {c}" for c in r2.columns]
        parts.append(f"## {split}\n\n{md_table(wide.join(r2).reset_index())}\n")
    parts.append("## Decision agreement\n\nPredicted circuit fields fed into the unchanged Phase 1 rules, "
                 "compared with decisions from exact transpiled fields. Exact transpile times were measured "
                 "with several transpiles running in parallel, so they overstate single-run cost somewhat.\n\n"
                 + md_table(agree, floatfmt=".3g") + "\n")
    if log is not None:
        outcomes = outcome_models(log)
        if len(outcomes):
            parts.append("## Execution-outcome models (runtime, energy, error)\n\n"
                         "Leave-one-out fits on the hybrid runs in `logs/decisions.csv`. These labels need a full "
                         "hybrid run each, so the dataset is small; read n before the numbers.\n\n"
                         + md_table(outcomes) + "\n")
    return "\n".join(parts)


def phase3() -> str:
    from sklearn.tree import export_text

    from hybrid_mapper import allocate as al
    from hybrid_mapper.environment import load_environment

    tasks = al.load_tasks()
    env = load_environment()
    results = {name: al.evaluate_split(tr, te) for name, (tr, te) in al.splits(tasks).items()}
    first = next(iter(results.values()))
    labels = tasks.oracle_label.value_counts()
    by_family = tasks.groupby(["family", "oracle_label"]).size().unstack(fill_value=0).reset_index()
    parts = [f"""# Phase 3 results: AI task allocation

Generated by `python -m hybrid_mapper report` from `data/tasks.csv`: {len(tasks)} tasks
({tasks.workload_id.nunique()} transpiled workloads x {env['scenarios']['per_workload']} sampled operating
conditions). Labels come from the ground-truth model in `hybrid_mapper/environment.py` /
`config/environment.yaml`, which simulates effects the Phase 1 rules ignore: exact MPS simulation of weakly
entangled circuits, the Goemans-Williamson Max-Cut heuristic, an HPC node's memory, readout error on sampling,
the shots-for-fidelity trade-off, and random queue waits. **This is a simulation study: the oracle stands in
for real execution feedback until Phase 5.**

Oracle labels: {", ".join(f"{k} {v} ({v / len(tasks):.0%})" for k, v in labels.items())}.

{md_table(by_family)}

Regret = extra cost (J = time + 0.001·energy + 10·QPU-seconds, from `rules.yaml`) over the oracle's choice;
a decision that yields no accepted result also pays a {env['scenarios']['failure_penalty_s']} s penalty.
"""]
    for name, r in results.items():
        table = pd.DataFrame(r["metrics"]).reset_index().rename(columns={"index": "Metric"})
        parts.append(f"## Held-out evaluation: {name}\n\n{md_table(table)}\n")
    parts.append("## Why the rules disagree with the oracle (random split)\n\n"
                 + md_table(al.disagreements(first, "Rules (exact transpile)")) + "\n")
    parts.append("## Where the gradient-boosting allocator still errs (random split)\n\n"
                 + md_table(al.disagreements(first, "AI: gradient boosting")) + "\n")
    for who in ("Rules (exact transpile)", "AI: gradient boosting"):
        parts.append(f"### Confusion matrix: {who}\n\n"
                     + md_table(al.confusion(first, who).reset_index().rename(columns={"index": ""})) + "\n")
    tuned = first["tuned"]
    parts.append(f"""## Tuned thresholds (augment, random split)

Grid search over `rules.yaml` minimising training regret chose statevector memory
{tuned['statevector_memory_gib']} GiB and F_min = {tuned['fidelity_min']}. Tuning helps a little, but no
threshold can express "weakly entangled circuits are classically easy": that needs features the rules lack.

## The learned decision tree (replace, random split)

Depth-4 tree, readable as if-then rules:

```
{export_text(first["tree"], feature_names=list(first["X_test"].columns), decimals=3)}
```

## What the gradient-boosting allocator relies on (permutation importance, random split)

{md_table(al.importance(first))}
""")
    fc = al.feedback_curve(tasks)
    parts.append("## Feedback curve: learning from new execution data (Function 6)\n\n"
                 "Start from the extrapolation split (train on <= 40 qubits). Move a share of the larger "
                 "workloads into training as execution feedback; score on a fixed 70% of large workloads "
                 "that are never fed back.\n\nMean regret:\n\n"
                 + md_table(fc.pivot(index="feedback (share of large workloads)", columns="allocator",
                                     values="regret").reset_index())
                 + "\n\nDecision accuracy:\n\n"
                 + md_table(fc.pivot(index="feedback (share of large workloads)", columns="allocator",
                                     values="accuracy").reset_index()) + "\n")
    return "\n".join(parts)


def run() -> None:
    RESULTS.mkdir(exist_ok=True)
    log = pd.read_csv(LOG_PATH) if LOG_PATH.exists() else None
    if log is not None:
        (RESULTS / "phase1_baselines.md").write_text(phase1(log))
        print("wrote results/phase1_baselines.md")
    else:
        print("no logs/decisions.csv yet: run `python -m hybrid_mapper baselines` for the Phase 1 table")
    (RESULTS / "phase2_prediction.md").write_text(phase2(load_dataset(include_timeouts=True), log))
    print("wrote results/phase2_prediction.md")
    from hybrid_mapper.allocate import TASKS_PATH

    if TASKS_PATH.exists():
        (RESULTS / "phase3_allocation.md").write_text(phase3())
        print("wrote results/phase3_allocation.md")
    else:
        print("no data/tasks.csv yet: run `python -m hybrid_mapper tasks` for the Phase 3 report")
